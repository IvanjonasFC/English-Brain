class VocabularyItem {
  final String term;
  final String ipa;
  final String definition;
  final String exampleSentence;
  final String spanishHint;
  final String category;
  final String difficulty;
  final List<String> relatedTerms;
  final String? origin;

  const VocabularyItem({
    required this.term,
    required this.ipa,
    required this.definition,
    required this.exampleSentence,
    required this.spanishHint,
    required this.category,
    required this.difficulty,
    this.relatedTerms = const [],
    this.origin,
  });

  factory VocabularyItem.fromJson(Map<String, dynamic> j) => VocabularyItem(
        term: j['term'] as String,
        ipa: (j['ipa'] ?? '') as String,
        definition: (j['definition'] ?? '') as String,
        exampleSentence: (j['exampleSentence'] ?? '') as String,
        spanishHint: (j['spanishHint'] ?? '') as String,
        category: (j['category'] ?? '') as String,
        difficulty: (j['difficulty'] ?? '') as String,
        relatedTerms: ((j['relatedTerms'] ?? []) as List).map((e) => e.toString()).toList(),
        origin: j['origin'] as String?,
      );
}

/// Track (recorrido) de un pack, derivado del sufijo del `level`
/// ("… • General", "… • Systems", "… • Executive", …).
enum VocabTrack { general, tech }

/// Utilidades CEFR robustas: parsean el `level` de display
/// (p.ej. "B1-B2 • Systems") en una banda [lo, hi] sobre la escalera
/// A1 < A2 < B1 < B2 < C1 < C2 y comparan por **solapamiento** de rangos,
/// en lugar del frágil match por substring. Retrocompatibles: no requieren
/// cambios en los datos (seed/asset/backend).
class Cefr {
  static const List<String> ladder = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

  static int? _ordinal(String raw) {
    final t = raw.trim().toUpperCase();
    final i = ladder.indexOf(t);
    return i == -1 ? null : i;
  }

  /// Extrae la parte CEFR (antes del "•") y devuelve [lo, hi] como ordinales.
  /// Si no puede parsear, devuelve el rango completo (no filtra de mas).
  static List<int> bandOf(String levelString) {
    final cefrPart = levelString.split('•').first.trim();
    final bits =
        cefrPart.split('-').map((e) => _ordinal(e)).whereType<int>().toList();
    if (bits.isEmpty) return [0, ladder.length - 1];
    final lo = bits.reduce((a, b) => a < b ? a : b);
    final hi = bits.reduce((a, b) => a > b ? a : b);
    return [lo, hi];
  }

  /// El pack (con este `level`) encaja con la pildora seleccionada?
  /// 'all' siempre encaja; el resto compara por solapamiento de intervalos.
  static bool matchesPill(String levelString, String pill) {
    if (pill.toLowerCase() == 'all') return true;
    // 1:1 con las 4 bandas del motor: el contenido pertenece al mismo cubo
    // que la píldora (mismo parse que usa el PracticeEngine).
    return DifficultyBandX.parse(levelString) == DifficultyBandX.parse(pill);
  }

  /// Track a partir del sufijo tras "•". Solo "General" es general; el resto
  /// (Systems, AI Engineer, Architect, Security Engineer, Senior, Junior,
  /// Workplace, Executive…) se considera tech/profesional.
  static VocabTrack trackOf(String levelString) {
    final parts = levelString.split('•');
    final suffix = (parts.length > 1 ? parts[1] : '').trim().toLowerCase();
    return suffix == 'general' ? VocabTrack.general : VocabTrack.tech;
  }
}

class VocabularyPack {
  final String id;
  final String title;
  final String description;
  final IconData icon;
  final String level;
  final Color accentColor;
  final List<VocabularyItem> terms;

  const VocabularyPack({
    required this.id,
    required this.title,
    required this.description,
    required this.icon,
    required this.level,
    required this.accentColor,
    required this.terms,
  });

  int get totalTerms => terms.length;

  /// Track derivado del `level` ("… • General" -> general; resto -> tech).
  VocabTrack get track => Cefr.trackOf(level);

  /// Banda CEFR [lo, hi] sobre la escalera de `Cefr.ladder`.
  List<int> get cefrBand => Cefr.bandOf(level);

  /// Encaja este pack con la pildora CEFR seleccionada ('all','A1-A2',…).
  bool matchesCefrPill(String pill) => Cefr.matchesPill(level, pill);

  static IconData _resolvePackIcon(int? cp) {
    if (cp == null) return Icons.school_rounded;
    switch (cp) {
      case 0xe86f: return Icons.code_rounded;
      case 0xe30c: return Icons.computer_rounded;
      case 0xe31e: return Icons.corporate_fare_rounded;
      case 0xe80b: return Icons.public_rounded;
      case 0xe0cb: return Icons.forum_rounded;
      case 0xe8e8: return Icons.verified_rounded;
      case 0xe897: return Icons.menu_book_rounded;
      case 0xe40a: return Icons.palette_rounded;
      case 0xe491: return Icons.people_rounded;
      case 0xe8cc: return Icons.shopping_bag_rounded;
      case 0xe80d: return Icons.wb_sunny_rounded;
      case 0xe570: return Icons.directions_bus_rounded;
      case 0xe8af: return Icons.thumb_up_rounded;
      case 0xe889: return Icons.history_rounded;
      case 0xe878: return Icons.event_rounded;
      case 0xe0af: return Icons.business_center_rounded;
      case 0xe872: return Icons.favorite_rounded;
      case 0xe88a: return Icons.home_rounded;
      case 0xe85d: return Icons.star_rounded;
      case 0xe556: return Icons.restaurant_rounded;
      case 0xe192: return Icons.access_time_rounded;
      case 0xe32a: return Icons.security_rounded;
      case 0xe869: return Icons.build_rounded;
      case 0xe1db: return Icons.dns_rounded;
      case 0xe880: return Icons.storage_rounded;
      case 0xe868: return Icons.cloud_rounded;
      case 0xe7ef: return Icons.groups_rounded;
      case 0xe859: return Icons.psychology_rounded;
      case 0xe324: return Icons.hub_rounded;
      case 0xe158: return Icons.email_rounded;
      case 0xe8b8: return Icons.record_voice_over_rounded;
      case 0xe24b: return Icons.query_stats_rounded;
      case 0xe87c: return Icons.help_outline_rounded;
      default: return Icons.school_rounded;
    }
  }

  factory VocabularyPack.fromJson(Map<String, dynamic> j) {
    return VocabularyPack(
      id: j['id'] as String,
      title: j['title'] as String,
      description: j['description'] as String,
      icon: _resolvePackIcon(j['iconCodePoint'] as int?),
      level: j['level'] as String,
      accentColor: Color(j['accentColorValue'] as int),
      terms: (j['terms'] as List).map((e) => VocabularyItem.fromJson(e as Map<String, dynamic>)).toList(),
    );
  }
}

